--
-- actions/init/init_emit.lua
-- Translates validated wizard state (Steps 1..4) into a clean, valid
-- cmake-bns.lua script ready for the baking engine and backends.
--

	local p = premake
	p.init = p.init or {}
	p.init.emit = {}
	local emit = p.init.emit


	local function quote(s)
		s = tostring(s or "")
		s = s:gsub("\\", "\\\\")
		s = s:gsub('"', '\\"')
		s = s:gsub("\n", "\\n")
		s = s:gsub("\r", "\\r")
		s = s:gsub("\t", "\\t")
		return '"' .. s .. '"'
	end


	local function emitCall(lines, indent, fnName, value)
		local pad = string.rep("   ", indent)
		table.insert(lines, string.format("%s%s %s", pad, fnName, quote(value)))
	end


	local function emitList(lines, indent, fnName, list)
		if not list or #list == 0 then
			return
		end
		local pad = string.rep("   ", indent)
		if #list <= 3 then
			local parts = {}
			for i = 1, #list do
				parts[i] = quote(list[i])
			end
			table.insert(lines, string.format("%s%s { %s }", pad, fnName, table.concat(parts, ", ")))
		else
			table.insert(lines, string.format("%s%s {", pad, fnName))
			local innerPad = string.rep("   ", indent + 1)
			for i = 1, #list do
				table.insert(lines, string.format("%s%s,", innerPad, quote(list[i])))
			end
			table.insert(lines, string.format("%s}", pad))
		end
	end


	local function hasAnyItems(tbl)
		if not tbl then return false end
		for _, v in pairs(tbl) do
			if type(v) == "table" and #v > 0 then
				return true
			elseif type(v) ~= "table" and v ~= nil and v ~= "" then
				return true
			end
		end
		return false
	end


---
-- Generate the full cmake-bns.lua source code from wizard state.
-- @param state { step1 = ..., step2 = ..., step3 = ..., step4 = ... }
---
	function emit.generateLua(state)
		local s1 = state.step1
		local s2 = state.step2 or { exports = {}, deps = {}, subprojects = {} }
		local s3 = state.step3 or { compiler = {}, platforms = {}, targetOverrides = {} }
		local s4 = state.step4 or { debug = {}, hooks = {} }

		local wks = s1.workspace
		local comp = s3.compiler or {}

		-- Index targets by name so we know sibling kinds & exports when wiring `links` / `uses`
		local targetByName = {}
		local startProject = nil
		for _, t in ipairs(s1.targets) do
			targetByName[t.name] = t
			if not startProject and (t.kind == "ConsoleApp" or t.kind == "WindowedApp") then
				startProject = t.name
			end
		end
		startProject = startProject or s1.targets[1].name

		local lines = {
			"-- cmake-bns.lua",
			"-- Generated by `cmake-bns init`.",
			"-- Run `cmake-bns gmake`, `cmake-bns ninja`, `cmake-bns vs2022`, or `cmake-bns xcode4` to generate build files.",
			"",
		}

		-- =====================================================================
		-- Workspace block
		-- =====================================================================
		emitCall(lines, 0, "workspace", wks.name)
		emitCall(lines, 1, "location", wks.buildDir)
		emitList(lines, 1, "configurations", wks.modes)
		emitCall(lines, 1, "defaultconfiguration", wks.modes[1])
		emitList(lines, 1, "platforms", wks.archs)
		emitCall(lines, 1, "startproject", startProject)
		table.insert(lines, "")

		emitCall(lines, 1, "multiprocessorcompile", "On")
		if comp.warnings then
			emitCall(lines, 1, "warnings", comp.warnings)
		end
		if comp.warningsAsErrors then
			emitList(lines, 1, "fatalwarnings", { "All" })
		end
		if comp.rtti then
			emitCall(lines, 1, "rtti", comp.rtti)
		end
		if comp.exceptions then
			emitCall(lines, 1, "exceptionhandling", comp.exceptions)
		end
		if comp.staticRuntime then
			emitCall(lines, 1, "staticruntime", comp.staticRuntime)
		end

		-- Architecture filters per platform
		for _, arch in ipairs(wks.archs) do
			table.insert(lines, "")
			emitCall(lines, 1, "filter", "platforms:" .. arch)
			emitCall(lines, 2, "architecture", arch)
		end

		-- Mode presets
		for _, mode in ipairs(wks.modes) do
			local mlow = mode:lower()
			table.insert(lines, "")
			emitCall(lines, 1, "filter", "configurations:" .. mode)
			if mlow == "debug" then
				emitList(lines, 2, "defines", { "DEBUG", "_DEBUG" })
				emitCall(lines, 2, "symbols", "On")
				emitCall(lines, 2, "optimize", "Off")
				emitCall(lines, 2, "runtime", "Debug")
				if comp.debugSanitizers and #comp.debugSanitizers > 0 then
					emitList(lines, 2, "sanitize", comp.debugSanitizers)
				end
			elseif mlow == "release" then
				emitList(lines, 2, "defines", { "NDEBUG" })
				emitCall(lines, 2, "symbols", "Off")
				emitCall(lines, 2, "optimize", "Full")
				emitCall(lines, 2, "runtime", "Release")
				if comp.ltoInRelease then
					emitCall(lines, 2, "linktimeoptimization", "On")
				end
			elseif mlow == "relwithdebinfo" then
				emitList(lines, 2, "defines", { "NDEBUG" })
				emitCall(lines, 2, "symbols", "On")
				emitCall(lines, 2, "optimize", "Speed")
				emitCall(lines, 2, "runtime", "Release")
			elseif mlow == "minsizerel" then
				emitList(lines, 2, "defines", { "NDEBUG" })
				emitCall(lines, 2, "symbols", "Off")
				emitCall(lines, 2, "optimize", "Size")
				emitCall(lines, 2, "runtime", "Release")
			end
		end

		-- Sensible Unicode default for Visual Studio on Windows
		table.insert(lines, "")
		emitList(lines, 1, "filter", { "system:windows", "action:vs*" })
		emitCall(lines, 2, "characterset", "Unicode")

		-- Workspace-level OS overrides from Step 3
		local osMap = {
			{ key = "windows", premakeOs = "windows" },
			{ key = "linux",   premakeOs = "linux" },
			{ key = "macos",   premakeOs = "macosx" },
		}
		for _, osEntry in ipairs(osMap) do
			local pblk = s3.platforms and s3.platforms[osEntry.key]
			if hasAnyItems(pblk) then
				table.insert(lines, "")
				emitCall(lines, 1, "filter", "system:" .. osEntry.premakeOs)
				emitList(lines, 2, "defines", pblk.defines)
				emitList(lines, 2, "removefiles", pblk.excludeSources)
				emitList(lines, 2, "buildoptions", pblk.compilerFlags)
				emitList(lines, 2, "linkoptions", pblk.linkerFlags)
			end
		end

		table.insert(lines, "")
		table.insert(lines, "   filter {}")

		-- External Premake subprojects from Step 2
		if s2.subprojects and #s2.subprojects > 0 then
			table.insert(lines, "")
			for _, sub in ipairs(s2.subprojects) do
				emitCall(lines, 0, "include", sub)
			end
		end

		-- =====================================================================
		-- Target project blocks
		-- =====================================================================
		for _, t in ipairs(s1.targets) do
			local tdeps  = (s2.deps and s2.deps[t.name]) or {}
			local texps  = (s2.exports and s2.exports[t.name]) or {}
			local tovr   = (s3.targetOverrides and s3.targetOverrides[t.name]) or {}
			local tdbg   = (s4.debug and s4.debug[t.name]) or {}
			local thooks = (s4.hooks and s4.hooks[t.name]) or {}

			table.insert(lines, "")
			table.insert(lines, "-- ============================================================================")
			table.insert(lines, string.format("-- Target: %s (%s)", t.name, t.kind))
			table.insert(lines, "-- ============================================================================")

			emitCall(lines, 0, "project", t.name)
			emitCall(lines, 1, "kind", t.kind)
			emitCall(lines, 1, "language", t.language)
			if t.cdialect then
				emitCall(lines, 1, "cdialect", t.cdialect)
			end
			if t.cppdialect then
				emitCall(lines, 1, "cppdialect", t.cppdialect)
			end

			emitCall(lines, 1, "targetdir", "bin/%{cfg.platform}/%{cfg.buildcfg}")
			emitCall(lines, 1, "objdir", wks.buildDir .. "/obj/%{cfg.platform}/%{cfg.buildcfg}/" .. t.name)

			if #t.sources > 0 then
				table.insert(lines, "")
				emitList(lines, 1, "files", t.sources)
			end
			emitList(lines, 1, "removefiles", tovr.excludeSources)
			emitList(lines, 1, "includedirs", t.includes)
			emitList(lines, 1, "externalincludedirs", tdeps.systemIncludes)
			emitList(lines, 1, "libdirs", tdeps.libDirs)
			emitList(lines, 1, "defines", tovr.defines)

			if tovr.pchHeader then
				emitCall(lines, 1, "pchheader", tovr.pchHeader)
			end
			if tovr.pchSource then
				emitCall(lines, 1, "pchsource", tovr.pchSource)
			end

			emitList(lines, 1, "buildoptions", tovr.compilerFlags)
			emitList(lines, 1, "linkoptions", tovr.linkerFlags)

			-- Separate linkable targets/libs vs header-only `uses` targets
			local actualLinks = {}
			local usesList = {}
			for _, lnk in ipairs(tdeps.links or {}) do
				local sibling = targetByName[lnk]
				if sibling and sibling.kind == "None" then
					-- Header-only sibling: consume its INTERFACE usage instead of linker input
					if not table.contains(usesList, lnk) then
						table.insert(usesList, lnk)
					end
				else
					table.insert(actualLinks, lnk)
					if sibling and s2.exports and hasAnyItems(s2.exports[lnk]) then
						if not table.contains(usesList, lnk) then
							table.insert(usesList, lnk)
						end
					end
				end
			end

			emitList(lines, 1, "links", actualLinks)
			emitList(lines, 1, "uses", usesList)

			-- Debugger settings (Step 4)
			if tdbg.workingDir then
				emitCall(lines, 1, "debugdir", tdbg.workingDir)
			end
			if tdbg.command then
				emitCall(lines, 1, "debugcommand", tdbg.command)
			end
			emitList(lines, 1, "debugargs", tdbg.args)
			emitList(lines, 1, "debugenvs", tdbg.env)

			-- Build lifecycle hooks (Step 4)
			emitList(lines, 1, "prebuildcommands", thooks.preBuild)
			emitList(lines, 1, "prelinkcommands", thooks.preLink)
			emitList(lines, 1, "postbuildcommands", thooks.postBuild)

			-- Public / Interface Exports (Step 2)
			if hasAnyItems(texps) then
				local usageKind = (t.kind == "None") and "INTERFACE" or "PUBLIC"
				table.insert(lines, "")
				emitCall(lines, 1, "usage", usageKind)
				emitList(lines, 2, "includedirs", texps.publicIncludes)
				emitList(lines, 2, "defines", texps.publicDefines)
				-- Re-activate project scope after usage block
				emitCall(lines, 0, "project", t.name)
			end

			-- OS-specific links from Step 2
			local hasOsLinks = false
			if tdeps.windowsLinks and #tdeps.windowsLinks > 0 then
				hasOsLinks = true
				table.insert(lines, "")
				emitCall(lines, 1, "filter", "system:windows")
				emitList(lines, 2, "links", tdeps.windowsLinks)
			end
			if tdeps.linuxLinks and #tdeps.linuxLinks > 0 then
				hasOsLinks = true
				table.insert(lines, "")
				emitCall(lines, 1, "filter", "system:linux")
				emitList(lines, 2, "links", tdeps.linuxLinks)
			end
			if tdeps.macosLinks and #tdeps.macosLinks > 0 then
				hasOsLinks = true
				table.insert(lines, "")
				emitCall(lines, 1, "filter", "system:macosx")
				emitList(lines, 2, "links", tdeps.macosLinks)
			end

			if hasOsLinks then
				table.insert(lines, "")
				table.insert(lines, "   filter {}")
			end
		end

		table.insert(lines, "")
		return table.concat(lines, "\n")
	end
